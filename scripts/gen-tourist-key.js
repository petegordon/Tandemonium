#!/usr/bin/env node
// ============================================================
// gen-tourist-key — inject the Google Map Tiles API key into a
// gitignored browser module so Tourist Mode (#333) can stream
// Photorealistic 3D Tiles without the secret ever entering git.
//
//   1. Reads GOOGLE_MAPS_API_KEY from .env (gitignored)
//   2. Writes js/tourist-key.local.js (gitignored) which sets
//      window.__TOURIST_MAPS_KEY__ for tourist-config.js to read
//
// Run:  npm run gen-tourist-key
// ============================================================

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');
const OUT_PATH = path.join(ROOT, 'js', 'tourist-key.local.js');

function readEnvKey(name) {
  if (!fs.existsSync(ENV_PATH)) return null;
  const text = fs.readFileSync(ENV_PATH, 'utf8');
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    if (line.slice(0, eq).trim() !== name) continue;
    let val = line.slice(eq + 1).trim();
    // Strip surrounding quotes if present
    if ((val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    return val;
  }
  return null;
}

const key = readEnvKey('GOOGLE_MAPS_API_KEY');

if (!key) {
  console.error('[gen-tourist-key] GOOGLE_MAPS_API_KEY not found in .env');
  console.error('  Add a line like:  GOOGLE_MAPS_API_KEY=AIza...');
  process.exit(1);
}

// JSON.stringify safely escapes the key into a JS string literal.
const banner = '// AUTO-GENERATED by scripts/gen-tourist-key.js — DO NOT COMMIT (gitignored).\n';
const body = `window.__TOURIST_MAPS_KEY__ = ${JSON.stringify(key)};\n`;
fs.writeFileSync(OUT_PATH, banner + body);

console.log(`[gen-tourist-key] wrote ${path.relative(ROOT, OUT_PATH)} (key length ${key.length})`);

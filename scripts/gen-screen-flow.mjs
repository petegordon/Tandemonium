#!/usr/bin/env node
// ============================================================
// gen-screen-flow.mjs — generate the lobby step table in docs/screen-flow.md
// ============================================================
//
// The lobby's steps are <uf-step>s inside <uf-flow id="lobby-flow"> in
// index.html, and every transition is a `_showStep(this.xStep)` call in
// js/lobby.js. This reads both and rewrites the block between the
// `<!-- generated:lobby-steps -->` markers in docs/screen-flow.md, so the
// step list, each step's back target and the methods that lead to it never
// drift from the code again. The hand-written flow diagrams below the block
// stay as they are.
//
//   npm run docs:screen-flow            # rewrite the block
//   npm run docs:screen-flow -- --check # exit 1 if the block is stale (CI)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const lobby = fs.readFileSync(path.join(ROOT, 'js', 'lobby.js'), 'utf8');
const docPath = path.join(ROOT, 'docs', 'screen-flow.md');
const check = process.argv.includes('--check');
const CR = String.fromCharCode(13), LF = String.fromCharCode(10);

// Steps: id + the SCREEN comment title above it + its first prompt text.
const steps = [];
const flowBlock = (html.match(/<uf-flow id="lobby-flow"[^>]*>([\s\S]*?)<\/uf-flow>/) || [])[1] || '';
const initial = (html.match(/<uf-flow id="lobby-flow"[^>]*current="([^"]+)"/) || [])[1] || '';
for (const m of flowBlock.matchAll(/<uf-step id="([^"]+)"[^>]*>([\s\S]*?)<\/uf-step>/g)) {
  const id = m[1];
  const before = html.slice(0, html.indexOf(m[0]));
  const titles = [...before.matchAll(/SCREEN:\s*([^\r\n(]+?)\s*\(#[a-z-]+\)/g)];   // nearest SCREEN comment above the step
  const title = titles.length ? titles[titles.length - 1][1] : id;
  const prompt = (m[2].match(/class="lobby-prompt"[^>]*>([^<]*)</) || [])[1] || '';
  steps.push({ id, title: title.trim(), prompt: prompt.trim() });
}
if (!steps.length) { console.error('no <uf-step>s found inside #lobby-flow'); process.exit(2); }

// Step property name ↔ id (this.modeStep = document.getElementById('lobby-mode'))
const propToId = {};
for (const m of lobby.matchAll(/this\.(\w+Step)\s*=\s*document\.getElementById\('([^']+)'\)/g)) propToId[m[1]] = m[2];

// Back targets: this._stepBack.set(this.xStep, document.getElementById('btn-…'))
const back = {};
for (const m of lobby.matchAll(/this\._stepBack\.set\(this\.(\w+Step),\s*(null|document\.getElementById\('([^']+)'\))\)/g)) back[propToId[m[1]]] = m[3] || null;

// Transitions: which methods call _showStep(this.xStep)
const leadsTo = {};
const methodRe = /^  (?:async )?(_?\w+)\s*\([^)]*\)\s*\{/gm;
const bounds = [];
let mm;
while ((mm = methodRe.exec(lobby))) bounds.push({ name: mm[1], at: mm.index });
for (let i = 0; i < bounds.length; i++) {
  const body = lobby.slice(bounds[i].at, bounds[i + 1] ? bounds[i + 1].at : undefined);
  for (const m of body.matchAll(/_showStep\(this\.(\w+Step)\)/g)) {
    const id = propToId[m[1]]; if (!id) continue;
    (leadsTo[id] ||= new Set()).add(bounds[i].name);
  }
}

const out = [];
out.push('<!-- generated:lobby-steps -->');
out.push('_Generated by `npm run docs:screen-flow` from `index.html` (`<uf-flow id="lobby-flow">`) and `js/lobby.js`. Do not edit by hand._');
out.push('');
out.push('| step (`<uf-step id>`) | screen | prompt | back button | shown by |');
out.push('|---|---|---|---|---|');
for (const s of steps) {
  const b = back[s.id] === undefined ? '' : (back[s.id] ? `\`#${back[s.id]}\`` : '— (root)');
  const by = [...(leadsTo[s.id] || [])].sort().map((n) => `\`${n}\``).join(', ') || '—';
  out.push(`| \`${s.id}\`${s.id === initial ? ' (initial)' : ''} | ${s.title} | ${s.prompt || '—'} | ${b} | ${by} |`);
}
out.push('');
out.push('One owner of "current step": `lobby.js` calls `_showStep(step)` → `flow.go(id)`; the flow\'s `uf-flow:change` event runs `_onStepShown` (monitors, PiP classes, carousel, difficulty selector, back hint, focus scope). Nothing else toggles a step\'s display.');
out.push('<!-- /generated:lobby-steps -->');

let doc = fs.readFileSync(docPath, 'utf8');
const eol = doc.includes(CR + LF) ? CR + LF : LF;
const block = out.join(eol);
const re = /<!-- generated:lobby-steps -->[\s\S]*?<!-- \/generated:lobby-steps -->/;
let next;
if (re.test(doc)) next = doc.replace(re, () => block);
else {
  // First run: replace the hand-written "## Lobby Screens (Steps)" code block.
  const old = /## Lobby Screens \(Steps\)\r?\n\r?\n```[\s\S]*?```\r?\n/;
  if (!old.test(doc)) { console.error('no insertion point in docs/screen-flow.md'); process.exit(2); }
  next = doc.replace(old, () => `## Lobby Screens (Steps)${eol}${eol}${block}${eol}`);
}
if (check) {
  if (next !== doc) { console.error('docs/screen-flow.md is stale — run `npm run docs:screen-flow`'); process.exit(1); }
  console.log('docs/screen-flow.md is up to date');
} else {
  fs.writeFileSync(docPath, next);
  console.log(`docs/screen-flow.md: ${steps.length} steps written`);
}
